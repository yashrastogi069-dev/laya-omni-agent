"""
omni_engine.decision.eval_corpus
================================
Versioned Decision Evaluation Corpus for System 1 nervous system, calibration,
and Hierarchical Capability Routing.

Covers 100+ systematically labeled cases across:
- Conversation / Informational
- Read-only file operations
- Local mutation & file edits
- High-risk system & destructive commands
- Browser automation & visual inspection
- Web research & scraping
- Software refactoring & code review
- Data analysis & SQLite operations
- n8n-like automation & multi-step quests
- Ambiguous references & missing parameter slots
- High urgency / low importance vs low urgency / high importance
- Negations and informational questions about dangerous commands
- Prompt injection & adversarial instruction override attacks
"""

from typing import Dict, List, Optional
from pydantic import Field
from omni_engine.contracts.base import BaseContractModel


class DecisionEvalCase(BaseContractModel):
    """A strongly typed, reviewable ground-truth decision evaluation case."""

    id: str = Field(..., description="Unique case identifier, e.g. 'case_001'")
    prompt: str = Field(..., description="Natural language user prompt or input text")
    category: str = Field(..., description="Evaluation category")
    expected_intent: str = Field(..., description="Expected intent: informational, task_execution, troubleshooting")
    expected_domain: str = Field(..., description="Expected primary domain: os, dev, web, browser, data, general")
    expected_risk: str = Field(..., description="Expected risk: safe_read_only, reversible_mutation, high_risk_system")
    expected_reversibility: str = Field(default="reversible", description="Expected reversibility: reversible, irreversible")
    expected_ambiguity: str = Field(default="unambiguous", description="Expected ambiguity: unambiguous, ambiguous")
    expected_needs_tools: bool = Field(default=True, description="Whether tools are required")
    expected_needs_plan: bool = Field(default=False, description="Whether multi-step DAG planning is required")
    expected_needs_clarification: bool = Field(default=False, description="Whether clarifying question is required")
    expected_skill: Optional[str] = Field(default=None, description="Expected canonical skill if template matches")
    is_adversarial: bool = Field(default=False, description="Whether case tests injection or adversarial framing")
    notes: Optional[str] = Field(default=None, description="Testing notes or rationale")


